/**
 * TV-38 — เรตโปรเว้นว่างตรงกลางไม่ได้
 *
 * rateStepsFromYearlyRates ให้ช่วงเวลาตาม "ลำดับใน array" ล้วน ๆ
 * และคนเรียกจะ filter ค่าว่างทิ้งก่อน ปีหลังจึงเลื่อนขึ้นมาแทนที่เงียบ ๆ
 * กรอกปี 1 กับปี 3 แล้วเว้นปี 2 = ปี 2 ใช้เรตของปี 3 และหมดโปรเร็วขึ้นเต็ม 1 ปี
 * ตัวเลขที่ได้ดูสมเหตุสมผลทุกอย่าง จึงไม่มีใครจับได้ถ้าไม่บล็อกตั้งแต่ต้น
 */

import { describe, expect, it } from 'vitest'
import { promoGap } from './model'

describe('promoGap', () => {
  it('กรอกครบไม่มีช่องโหว่', () => {
    expect(promoGap([2.5, 3.25, 3.75])).toBeNull()
  })

  it('ยังไม่กรอกอะไรเลย ไม่ใช่ช่องโหว่ — เป็นเรื่องของ blocking ปกติ', () => {
    expect(promoGap(['', '', ''])).toBeNull()
  })

  it('กรอกแค่ปีแรก ๆ ติดกัน ไม่ใช่ช่องโหว่ — โปรสั้นกว่า 3 ปีมีจริง', () => {
    expect(promoGap([2.5, '', ''])).toBeNull()
    expect(promoGap([2.5, 3.0, ''])).toBeNull()
  })

  it('เว้นปี 2 แล้วกรอกปี 3 = ช่องโหว่ที่ปี 2 (เคสที่ทำให้โปรหายไป 1 ปี)', () => {
    expect(promoGap([2.5, '', 3.75])).toBe(2)
  })

  it('เว้นปี 1 แล้วกรอกปี 2 = ช่องโหว่ที่ปี 1', () => {
    expect(promoGap(['', 3.0, 3.75])).toBe(1)
    expect(promoGap(['', '', 3.75])).toBe(1)
  })

  it('เว้นหลายช่อง รายงานช่องแรกสุด เพื่อให้ผู้ใช้ไล่แก้จากบนลงล่าง', () => {
    expect(promoGap(['', 3.0, '', 4.0])).toBe(1)
    expect(promoGap([2.5, '', '', 4.0])).toBe(2)
  })

  it('0% เป็นเรตที่ใช้ได้จริง ห้ามนับเป็นช่องว่าง', () => {
    expect(promoGap([0, '', 3.75])).toBe(2)
    expect(promoGap([2.5, 0, 3.75])).toBeNull()
  })
})
